import numpy as np
from scipy.integrate import solve_ivp
from .ode import double_pendulum_ode
from .utils import to_cartesian_state


def simulate_trajectory(theta1_0, omega1_0, theta2_0, omega2_0,
                        L1, L2, m1, m2, g, t):
    """
    Simulates a single double pendulum trajectory using solve_ivp.

    Returns:
        Angular state trajectory of shape (T, 4):
        [theta1, omega1, theta2, omega2]
    """
    z0 = [theta1_0, omega1_0, theta2_0, omega2_0]

    sol = solve_ivp(
        fun=lambda t, z: double_pendulum_ode(t, z, L1, L2, m1, m2, g),
        t_span=(t[0], t[-1]),
        y0=z0,
        t_eval=t,
        method="RK45",
        rtol=1e-9,
        atol=1e-9
    )

    return sol.y.T  # shape: (T, 4)


def scale_state(state):
    """
    Normalises Cartesian positions and velocities.

    Input:
        state: array of shape (T, 8)
               [x1, y1, x2, y2, vx1, vy1, vx2, vy2]

    Returns:
        Scaled state of shape (T, 8)
    """
    max_vals = np.array([
        2.0, 2.0,   # x1, y1
        2.0, 2.0,   # x2, y2
        5.0, 5.0,   # vx1, vy1
        5.0, 5.0    # vx2, vy2
    ])
    return state / max_vals


def build_sequences(data, seq_len):
    """
    Converts a trajectory into sliding-window sequences.

    Input:
        data: (T, 8) scaled Cartesian state
        seq_len: length of each input window

    Returns:
        X: (num_windows, seq_len, 8)
        y: (num_windows, 8)
    """
    X, y = [], []
    for i in range(len(data) - seq_len):
        X.append(data[i:i+seq_len])
        y.append(data[i+seq_len])
    return np.array(X), np.array(y)


def sample_initial_conditions(n_samples):
    """
    Samples random initial angular states.

    Returns:
        theta1_0, omega1_0, theta2_0, omega2_0
        each of shape (n_samples,)
    """
    theta1 = np.random.uniform(-np.pi, np.pi, n_samples)
    theta2 = np.random.uniform(-np.pi, np.pi, n_samples)
    omega1 = np.random.uniform(-1.0, 1.0, n_samples)
    omega2 = np.random.uniform(-1.0, 1.0, n_samples)
    return theta1, omega1, theta2, omega2


def build_multi_trajectory_dataset(n_traj, seq_len, L1=1.0, L2=1.0,
                                   m1=1.0, m2=1.0, g=9.81,
                                   tmax=50, dt=0.1):
    """
    Generates a dataset of multiple double pendulum trajectories.

    Returns:
        X_all: (total_samples, seq_len, 8)
        y_all: (total_samples, 8)
    """
    t = np.arange(0, tmax + dt, dt)

    theta1_0, omega1_0, theta2_0, omega2_0 = sample_initial_conditions(n_traj)

    X_all, y_all = [], []

    for i in range(n_traj):
        # Simulate angular trajectory
        traj = simulate_trajectory(
            theta1_0[i], omega1_0[i],
            theta2_0[i], omega2_0[i],
            L1, L2, m1, m2, g, t
        )

        # Convert to 8‑feature Cartesian state
        traj_cart = to_cartesian_state(traj, L1, L2)

        # Scale
        traj_scaled = scale_state(traj_cart)

        # Build sequences
        X, y = build_sequences(traj_scaled, seq_len)
        X_all.append(X)
        y_all.append(y)

    return np.vstack(X_all), np.vstack(y_all)